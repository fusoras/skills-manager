#[test]
fn add_dry_run_writes_nothing() {
    let (sandbox, _store, project) = ready();
    let before = tree(&project);

    let output = stdout_of(sandbox.skm_in(&project).args(["add", "alpha", "--dry-run"]));

    assert_eq!(
        output,
        "Would install alpha -> .agents/skills/alpha\n\
         Dry run: nothing was written.\n"
    );
    assert_eq!(tree(&project), before);
    assert_clean_project(&project);
    assert!(!project.join(".agents").exists());
}

#[test]
fn add_installs_several_skills_and_ignores_repeats() {
    let (sandbox, _store, project) = ready();

    let output = stdout_of(
        sandbox
            .skm_in(&project)
            .args(["add", "alpha", "beta", "alpha", "beta"]),
    );

    assert_eq!(
        output,
        "Installed alpha -> .agents/skills/alpha\n\
         Installed beta -> .agents/skills/beta\n"
    );
    assert!(project.join(".agents/skills/alpha/SKILL.md").is_file());
    assert!(project.join(".agents/skills/beta/SKILL.md").is_file());
    assert_clean_project(&project);

    let registry = sandbox.registry_text();
    assert_eq!(registry.matches("[[projects.").count(), 2, "{registry}");
}

#[test]
fn add_pin_marks_the_central_registry() {
    let (sandbox, _store, project) = ready();

    let output = stdout_of(sandbox.skm_in(&project).args(["add", "alpha", "--pin"]));

    assert_eq!(output, "Installed alpha -> .agents/skills/alpha (pinned)\n");
    assert_clean_project(&project);

    let registry = sandbox.registry_text();
    assert!(registry.contains("pinned = true\n"), "{registry}");

    // Re-adding without --pin must not silently unpin.
    let output = stdout_of(sandbox.skm_in(&project).args(["add", "alpha"]));
    assert!(output.ends_with("(pinned)\n"), "{output}");
    assert!(sandbox.registry_text().contains("pinned = true\n"));
    assert_clean_project(&project);
}

