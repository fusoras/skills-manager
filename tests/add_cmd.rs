//! End-to-end tests of `skm add`: real copies and central registry.
//! Projects remain 100% clean: no `skills.toml` and no `.skills-manager/`.

mod common;

use std::path::PathBuf;

use common::{
    DEFAULT_CONFIG, Sandbox, assert_clean_project, failure_of, is_executable, is_symlink, read,
    stdout_of, tree, value_of, write,
};

/// Flat store holding `alpha` (nested file, executable script and junk) and `beta`.
fn store(sandbox: &Sandbox, name: &str) -> PathBuf {
    let root = sandbox.path(name);
    sandbox.skill(&root, "alpha", Some("alpha"));
    write(&root.join("alpha/templates/base.md"), "template\n");
    write(&root.join("alpha/run.sh"), "#!/bin/sh\n");
    common::make_executable(&root.join("alpha/run.sh"));
    write(&root.join("alpha/node_modules/pkg/index.js"), "junk\n");
    write(&root.join("alpha/.git/config"), "junk\n");
    write(&root.join("alpha/scratch.tmp"), "junk\n");
    sandbox.skill(&root, "beta", None);
    root
}

/// A sandbox with the store of [`store`] registered as the global store.
fn ready() -> (Sandbox, PathBuf, PathBuf) {
    let sandbox = Sandbox::new();
    let store = store(&sandbox, "store");
    sandbox.register_store(&store);
    let project = sandbox.project();
    (sandbox, store, project)
}

#[test]
fn add_copies_real_files_and_records_in_central_registry() {
    let (sandbox, _store, project) = ready();

    let output = stdout_of(sandbox.skm_in(&project).args(["add", "alpha"]));
    assert_eq!(output, "Installed alpha -> .agents/skills/alpha\n");

    // Real copies: files with their content, permissions and no symlinks.
    let dest = project.join(".agents/skills/alpha");
    assert_eq!(
        read(&dest.join("SKILL.md")),
        "---\nname: alpha\ndescription: test skill\n---\n\n# Body\n"
    );
    assert_eq!(read(&dest.join("templates/base.md")), "template\n");
    assert!(!is_symlink(&dest), "the copy must not be a symlink");
    assert!(!is_symlink(&dest.join("SKILL.md")));
    assert!(is_executable(&dest.join("run.sh")));
    assert!(!dest.join("node_modules").exists());
    assert!(!dest.join(".git").exists());
    assert!(!dest.join("scratch.tmp").exists());

    // Project root is completely clean!
    assert_clean_project(&project);

    // No leftovers of the atomic install.
    assert!(
        tree(&project).iter().all(|entry| !entry.contains("skm-")),
        "{:?}",
        tree(&project)
    );

    // Central registry records what was written.
    let registry = sandbox.registry_text();
    assert!(
        registry.starts_with("# Generated by skm; do not edit.\n"),
        "{registry}"
    );
    assert!(registry.contains("name = \"alpha\""), "{registry}");
    assert!(
        registry.contains("target = \".agents/skills\""),
        "{registry}"
    );

    let written = value_of(&registry, "written_hash");
    assert!(written.starts_with("blake3:"), "{written}");
    assert_eq!(
        written,
        value_of(&registry, "source_hash"),
        "a fresh copy has the content of the store:\n{registry}"
    );
    assert!(registry.contains("pinned = false\n"), "{registry}");
}

#[test]
fn add_again_re_syncs_without_rewriting_anything() {
    let (sandbox, _store, project) = ready();
    stdout_of(sandbox.skm_in(&project).args(["add", "alpha"]));
    let before_registry = sandbox.registry_text();

    let output = stdout_of(sandbox.skm_in(&project).args(["add", "alpha"]));

    assert_eq!(output, "Re-synced alpha -> .agents/skills/alpha\n");
    assert_eq!(sandbox.registry_text(), before_registry);
    assert_clean_project(&project);
}

#[test]
fn add_refuses_local_modifications_unless_forced() {
    let (sandbox, _store, project) = ready();
    stdout_of(sandbox.skm_in(&project).args(["add", "alpha"]));
    let local = project.join(".agents/skills/alpha/notes.md");
    write(&local, "local work\n");

    let (stdout, stderr) = failure_of(sandbox.skm_in(&project).args(["add", "alpha"]));
    assert_eq!(stdout, "");
    assert!(
        stderr.contains(
            "error: skill 'alpha' was modified in .agents/skills/alpha; \
             pass --force to overwrite it or run `skm remove alpha`"
        ),
        "{stderr}"
    );
    assert_eq!(
        read(&local),
        "local work\n",
        "the error must not touch files"
    );
    assert!(local.exists());

    let output = stdout_of(sandbox.skm_in(&project).args(["add", "alpha", "--force"]));
    assert_eq!(output, "Replaced alpha -> .agents/skills/alpha\n");
    assert!(
        !local.exists(),
        "the forced install replaces the whole tree"
    );
    assert_clean_project(&project);
}

#[test]
fn add_needs_force_for_a_directory_skm_did_not_write() {
    let (sandbox, _store, project) = ready();
    write(
        &project.join(".agents/skills/alpha/handwritten.md"),
        "mine\n",
    );

    let (_, stderr) = failure_of(sandbox.skm_in(&project).args(["add", "alpha"]));
    assert!(
        stderr.contains(
            "error: .agents/skills/alpha already exists but is not managed by skm; \
             pass --force to overwrite it"
        ),
        "{stderr}"
    );

    let output = stdout_of(sandbox.skm_in(&project).args(["add", "alpha", "--force"]));
    assert_eq!(output, "Replaced alpha -> .agents/skills/alpha\n");
    assert!(!project.join(".agents/skills/alpha/handwritten.md").exists());
    assert_clean_project(&project);
}

#[test]
fn add_follows_the_store_that_is_registered_now() {
    let (sandbox, _store, project) = ready();
    stdout_of(sandbox.skm_in(&project).args(["add", "alpha"]));

    let other = store(&sandbox, "other");
    sandbox.register_store(&other);

    let output = stdout_of(sandbox.skm_in(&project).args(["add", "alpha"]));
    assert_eq!(output, "Re-synced alpha -> .agents/skills/alpha\n");
    assert!(!project.join(".agents/skills/alpha/scratch.tmp").exists());

    stdout_of(sandbox.skm_in(&project).arg("sync"));
    assert!(
        project
            .join(".agents/skills/alpha/templates/base.md")
            .is_file()
    );
    assert_clean_project(&project);
}

