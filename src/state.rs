//! Local install state `.skills-manager/state.toml`.
//!
//! This file records what `skm` actually wrote, so it is machine owned and never
//! committed: managed projects should ignore `.skills-manager/`. Because nothing
//! in it is hand written, it is serialized with `toml` instead of `toml_edit`.
//!
//! ```toml
//! [[skill]]
//! name = "git-commit"
//! source_rel = "git-commit"
//! target = ".agents/skills"
//! written_hash = "blake3:..."
//! source_hash = "blake3:..."
//! pinned = false
//! installed_at = 1760536800
//! ```
//!
//! A copy the user edited on purpose is *detached*: the extra fields below turn
//! the entry into a tombstone, a fork that `skm` never touches nor adopts again.
//! They are omitted for every other entry.
//!
//! ```toml
//! [[skill]]
//! name = "draft"
//! source_rel = "draft"
//! target = ".agents/skills"
//! written_hash = "blake3:..."   # what skm wrote, or the content found
//! source_hash = "blake3:..."    # the store content that was not applied
//! pinned = false
//! installed_at = 1760536800
//! content_hash = "blake3:..."   # the local content at detach time
//! detached_at = 1760536800      # epoch seconds
//! detached = true
//! ```

use std::fs;
use std::io::ErrorKind;
use std::path::Path;

use anyhow::{Context, Result};
use serde::{Deserialize, Serialize};

/// First line of the generated file.
pub const HEADER: &str = "# Generated by skm; do not edit.\n";

/// Content of the state file.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct State {
    /// One entry per installed skill.
    #[serde(default, rename = "skill", skip_serializing_if = "Vec::is_empty")]
    pub skills: Vec<SkillState>,
}

/// One installed skill.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct SkillState {
    /// Skill name (frontmatter name, else the store directory name).
    pub name: String,
    /// Skill directory relative to the store root, `/` separated.
    pub source_rel: String,
    /// Install directory relative to the project root (or absolute).
    pub target: String,
    /// Hash of the content `skm` wrote into the project.
    pub written_hash: String,
    /// Hash of the store content at install time.
    pub source_hash: String,
    /// The user asked for this copy to stay untouched.
    #[serde(default)]
    pub pinned: bool,
    /// Install time, epoch seconds.
    pub installed_at: i64,
    /// Hash of the local content found when the copy was detached.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub content_hash: Option<String>,
    /// Detach time, epoch seconds.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub detached_at: Option<i64>,
    /// The copy is a local fork: sync ignores it for good.
    #[serde(default, skip_serializing_if = "is_false")]
    pub detached: bool,
}

fn is_false(value: &bool) -> bool {
    !*value
}

impl State {
    /// Entry of a skill installed into `target`.
    pub fn get(&self, name: &str, target: &str) -> Option<&SkillState> {
        self.skills
            .iter()
            .find(|entry| entry.name == name && entry.target == target)
    }

    /// Every entry of a skill, whatever its target.
    pub fn get_all(&self, name: &str) -> Vec<&SkillState> {
        self.skills
            .iter()
            .filter(|entry| entry.name == name)
            .collect()
    }

    /// Insert `entry`, replacing the entry for the same name and target.
    pub fn upsert(&mut self, entry: SkillState) {
        match self
            .skills
            .iter_mut()
            .find(|existing| existing.name == entry.name && existing.target == entry.target)
        {
            Some(existing) => *existing = entry,
            None => self.skills.push(entry),
        }
    }

    /// Remove and return the entry for `name` in `target`.
    pub fn remove(&mut self, name: &str, target: &str) -> Option<SkillState> {
        let index = self
            .skills
            .iter()
            .position(|entry| entry.name == name && entry.target == target)?;
        Some(self.skills.remove(index))
    }

    /// Targets that hold managed copies.
    pub fn targets(&self) -> Vec<&str> {
        let mut targets: Vec<&str> = self
            .skills
            .iter()
            .map(|entry| entry.target.as_str())
            .collect();
        targets.sort_unstable();
        targets.dedup();
        targets
    }
}

/// Current time in epoch seconds (no date crate needed).
pub fn now_epoch() -> i64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_or(0, |elapsed| elapsed.as_secs() as i64)
}

/// Load the state at `path`; a missing file yields an empty state.
pub fn load(path: &Path) -> Result<State> {
    match fs::read_to_string(path) {
        Ok(text) => {
            toml::from_str(&text).with_context(|| format!("invalid state file {}", path.display()))
        }
        Err(error) if error.kind() == ErrorKind::NotFound => Ok(State::default()),
        Err(error) => Err(error).with_context(|| format!("reading {}", path.display())),
    }
}

/// Persist `state`, sorted by name so the file is stable across runs.
pub fn save(path: &Path, state: &State) -> Result<()> {
    let mut sorted = state.clone();
    sorted
        .skills
        .sort_by(|a, b| a.name.cmp(&b.name).then_with(|| a.target.cmp(&b.target)));

    let text = toml::to_string_pretty(&sorted).context("serializing the state file")?;
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).with_context(|| format!("creating {}", parent.display()))?;
    }
    fs::write(path, format!("{HEADER}{text}"))
        .with_context(|| format!("writing {}", path.display()))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn entry(name: &str, target: &str) -> SkillState {
        SkillState {
            name: name.to_owned(),
            source_rel: name.to_owned(),
            target: target.to_owned(),
            written_hash: "blake3:aaaa".to_owned(),
            source_hash: "blake3:bbbb".to_owned(),
            pinned: false,
            installed_at: 1_760_536_800,
            ..SkillState::default()
        }
    }

    /// The entry of a copy the user forked: `detached` plus its two extra fields.
    fn tombstone(name: &str, target: &str) -> SkillState {
        SkillState {
            content_hash: Some("blake3:cccc".to_owned()),
            detached_at: Some(1_760_600_000),
            detached: true,
            ..entry(name, target)
        }
    }

    #[test]
    fn load_missing_state_is_empty() {
        let tmp = tempfile::tempdir().unwrap();
        assert_eq!(
            load(&tmp.path().join("state.toml")).unwrap(),
            State::default()
        );
    }

    #[test]
    fn save_and_load_roundtrip_with_the_documented_shape() {
        let tmp = tempfile::tempdir().unwrap();
        let path = tmp.path().join(".skills-manager").join("state.toml");
        let state = State {
            skills: vec![entry("git-commit", ".agents/skills")],
        };

        save(&path, &state).unwrap();

        assert_eq!(
            fs::read_to_string(&path).unwrap(),
            "# Generated by skm; do not edit.\n\
             [[skill]]\n\
             name = \"git-commit\"\n\
             source_rel = \"git-commit\"\n\
             target = \".agents/skills\"\n\
             written_hash = \"blake3:aaaa\"\n\
             source_hash = \"blake3:bbbb\"\n\
             pinned = false\n\
             installed_at = 1760536800\n"
        );
        assert_eq!(load(&path).unwrap(), state);
    }

    #[test]
    fn a_tombstone_serializes_with_the_three_extra_fields() {
        let tmp = tempfile::tempdir().unwrap();
        let path = tmp.path().join("state.toml");
        let state = State {
            skills: vec![tombstone("draft", ".agents/skills")],
        };

        save(&path, &state).unwrap();

        assert_eq!(
            fs::read_to_string(&path).unwrap(),
            "# Generated by skm; do not edit.\n\
             [[skill]]\n\
             name = \"draft\"\n\
             source_rel = \"draft\"\n\
             target = \".agents/skills\"\n\
             written_hash = \"blake3:aaaa\"\n\
             source_hash = \"blake3:bbbb\"\n\
             pinned = false\n\
             installed_at = 1760536800\n\
             content_hash = \"blake3:cccc\"\n\
             detached_at = 1760600000\n\
             detached = true\n"
        );
        let reloaded = load(&path).unwrap();
        assert_eq!(reloaded, state);
        assert_eq!(
            reloaded
                .get("draft", ".agents/skills")
                .unwrap()
                .content_hash,
            Some("blake3:cccc".to_owned())
        );
        assert_eq!(reloaded.targets(), [".agents/skills"]);
    }

    #[test]
    fn entries_without_the_extra_fields_stay_unattached() {
        let entry = entry("git-commit", ".agents/skills");
        assert!(!entry.detached);
        assert_eq!(entry.content_hash, None);
        assert_eq!(entry.detached_at, None);
    }

    #[test]
    fn save_sorts_entries_by_name_and_target() {
        let tmp = tempfile::tempdir().unwrap();
        let path = tmp.path().join("state.toml");
        let state = State {
            skills: vec![entry("zulu", "b"), entry("alpha", "b"), entry("alpha", "a")],
        };

        save(&path, &state).unwrap();

        let reloaded = load(&path).unwrap();
        let order: Vec<(&str, &str)> = reloaded
            .skills
            .iter()
            .map(|entry| (entry.name.as_str(), entry.target.as_str()))
            .collect();
        assert_eq!(order, [("alpha", "a"), ("alpha", "b"), ("zulu", "b")]);
    }

    #[test]
    fn load_reports_corrupt_state_with_the_path() {
        let tmp = tempfile::tempdir().unwrap();
        let path = tmp.path().join("state.toml");
        fs::write(&path, "[[skill]]\nname = \n").unwrap();

        let error = load(&path).unwrap_err().to_string();
        assert!(error.starts_with("invalid state file"), "{error}");
        assert!(error.contains("state.toml"), "{error}");
    }

    #[test]
    fn upsert_replaces_only_the_same_name_and_target() {
        let mut state = State::default();
        state.upsert(entry("a", "one"));
        state.upsert(entry("a", "two"));
        state.upsert(SkillState {
            written_hash: "blake3:cccc".to_owned(),
            pinned: true,
            ..entry("a", "one")
        });

        assert_eq!(state.skills.len(), 2);
        assert_eq!(state.get("a", "one").unwrap().written_hash, "blake3:cccc");
        assert!(state.get("a", "one").unwrap().pinned);
        assert_eq!(state.get("a", "two").unwrap().written_hash, "blake3:aaaa");
        assert!(state.get("a", "three").is_none());
    }

    #[test]
    fn remove_and_lookups() {
        let mut state = State::default();
        state.upsert(entry("a", "one"));
        state.upsert(entry("a", "two"));

        assert_eq!(state.get_all("a").len(), 2);
        assert_eq!(state.targets(), ["one", "two"]);

        let removed = state.remove("a", "one").unwrap();
        assert_eq!(removed.target, "one");
        assert!(state.remove("a", "one").is_none());
        assert_eq!(state.get_all("a").len(), 1);
        assert_eq!(state.targets(), ["two"]);
    }

    #[test]
    fn now_epoch_is_a_plausible_timestamp() {
        assert!(now_epoch() > 1_700_000_000);
    }
}
