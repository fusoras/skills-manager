//! Global project registry `~/.local/state/skm/projects.toml`.
//!
//! Stores the state of every project managed by `skm` on this machine.
//! Managed projects themselves remain 100% clean: no `skills.toml` and no
//! `.skills-manager/` directories are ever written into them.

use std::collections::BTreeMap;
use std::fs;
use std::io::ErrorKind;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};
use serde::{Deserialize, Serialize};

/// First line of the generated registry file.
pub const HEADER: &str = "# Generated by skm; do not edit.\n";

/// Subdirectory in XDG state home.
pub const STATE_SUBDIR: &str = "skm";

/// File name of the project registry.
pub const REGISTRY_FILE: &str = "projects.toml";

/// The central registry of all projects.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct Registry {
    /// Map from project key (e.g. `~/path/to/project` or `/var/www/project`)
    /// to its recorded configuration and installed skills.
    #[serde(
        default,
        rename = "projects",
        skip_serializing_if = "BTreeMap::is_empty"
    )]
    pub projects: BTreeMap<String, ProjectRecord>,
}

/// Recorded configuration and skills for a single project.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct ProjectRecord {
    /// Custom project-relative target directory for skills.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub target: Option<String>,
    /// Installed skills.
    #[serde(default, rename = "skill", skip_serializing_if = "Vec::is_empty")]
    pub skills: Vec<SkillState>,
}

/// One installed skill in a project.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct SkillState {
    /// Skill name (frontmatter name, else store directory name).
    pub name: String,
    /// Skill directory relative to the store root, `/` separated.
    pub source_rel: String,
    /// Install directory relative to the project root.
    pub target: String,
    /// Hash of the content written into the project.
    pub written_hash: String,
    /// Hash of the store content at install time.
    pub source_hash: String,
    /// Untouched by sync.
    #[serde(default)]
    pub pinned: bool,
    /// Install time, epoch seconds.
    pub installed_at: i64,
    /// Hash of the local content found when detached.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub content_hash: Option<String>,
    /// Detach time, epoch seconds.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub detached_at: Option<i64>,
    /// The copy is a local fork: sync leaves it alone for good.
    #[serde(default, skip_serializing_if = "is_false")]
    pub detached: bool,
}

fn is_false(value: &bool) -> bool {
    !*value
}

impl ProjectRecord {
    /// Entry of a skill installed into `target`.
    pub fn get(&self, name: &str, target: &str) -> Option<&SkillState> {
        self.skills
            .iter()
            .find(|entry| entry.name == name && entry.target == target)
    }

    /// Every entry of a skill, across all targets.
    pub fn get_all(&self, name: &str) -> Vec<&SkillState> {
        self.skills
            .iter()
            .filter(|entry| entry.name == name)
            .collect()
    }

    /// Insert `entry`, replacing any existing entry with the same name and target.
    pub fn upsert(&mut self, entry: SkillState) {
        match self
            .skills
            .iter_mut()
            .find(|existing| existing.name == entry.name && existing.target == entry.target)
        {
            Some(existing) => *existing = entry,
            None => self.skills.push(entry),
        }
    }

    /// Remove and return the entry for `name` in `target`.
    pub fn remove(&mut self, name: &str, target: &str) -> Option<SkillState> {
        let index = self
            .skills
            .iter()
            .position(|entry| entry.name == name && entry.target == target)?;
        Some(self.skills.remove(index))
    }

    /// Targets that hold managed copies.
    pub fn targets(&self) -> Vec<&str> {
        let mut targets: Vec<&str> = self
            .skills
            .iter()
            .map(|entry| entry.target.as_str())
            .collect();
        targets.sort_unstable();
        targets.dedup();
        targets
    }

    /// Returns `true` if there are no installed skills and no custom target.
    pub fn is_empty(&self) -> bool {
        self.skills.is_empty() && self.target.is_none()
    }
}

/// Current time in epoch seconds.
pub fn now_epoch() -> i64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_or(0, |elapsed| elapsed.as_secs() as i64)
}

/// Directory where the user state lives.
pub fn state_dir() -> Result<PathBuf> {
    if let Some(val) = std::env::var_os("XDG_STATE_HOME")
        && !val.is_empty()
    {
        return Ok(PathBuf::from(val));
    }
    if let Some(dir) = dirs::state_dir() {
        return Ok(dir);
    }
    if let Some(home) = dirs::home_dir() {
        return Ok(home.join(".local").join("state"));
    }
    bail!("cannot determine the user state directory (set XDG_STATE_HOME)")
}

/// Path to `projects.toml`.
pub fn path() -> Result<PathBuf> {
    Ok(path_in(&state_dir()?))
}

/// `<state_dir>/skm/projects.toml` for an explicit state directory.
pub fn path_in(state_dir: &Path) -> PathBuf {
    state_dir.join(STATE_SUBDIR).join(REGISTRY_FILE)
}

/// Normalize a project root path for use as a registry key.
/// Paths within the user home are saved as `~/...` for portability.
pub fn normalize_project_key(root: &Path) -> String {
    let canonical = root.canonicalize().unwrap_or_else(|_| root.to_path_buf());
    let home = dirs::home_dir();
    match home.and_then(|h| canonical.strip_prefix(h).ok()) {
        Some(rest) if rest.as_os_str().is_empty() => "~".to_owned(),
        Some(rest) => format!("~/{}", rest.to_string_lossy()),
        None => canonical.to_string_lossy().into_owned(),
    }
}

/// Resolve a project key back to a filesystem path.
pub fn resolve_project_key(key: &str) -> PathBuf {
    crate::store::expand_tilde(key)
}

impl Registry {
    /// Load the global project registry. Missing file yields an empty registry.
    pub fn load() -> Result<Self> {
        Self::load_from(&path()?)
    }

    /// Load the registry from a specific path.
    pub fn load_from(path: &Path) -> Result<Self> {
        match fs::read_to_string(path) {
            Ok(text) => toml::from_str(&text)
                .with_context(|| format!("invalid registry file {}", path.display())),
            Err(error) if error.kind() == ErrorKind::NotFound => Ok(Self::default()),
            Err(error) => Err(error).with_context(|| format!("reading {}", path.display())),
        }
    }

    /// Persist the registry to its default path.
    #[allow(dead_code)]
    pub fn save(&self) -> Result<()> {
        Self::save_to(self, &path()?)
    }

    /// Persist the registry to `path`.
    pub fn save_to(&self, path: &Path) -> Result<()> {
        let mut sorted = self.clone();
        for record in sorted.projects.values_mut() {
            record
                .skills
                .sort_by(|a, b| a.name.cmp(&b.name).then_with(|| a.target.cmp(&b.target)));
        }

        let text = toml::to_string_pretty(&sorted).context("serializing registry")?;
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)
                .with_context(|| format!("creating directory {}", parent.display()))?;
        }
        fs::write(path, format!("{HEADER}{text}"))
            .with_context(|| format!("writing {}", path.display()))
    }

    /// Find the project record matching `root`.
    pub fn get_project(&self, root: &Path) -> Option<&ProjectRecord> {
        let key = normalize_project_key(root);
        if let Some(record) = self.projects.get(&key) {
            return Some(record);
        }
        let canonical = root.canonicalize().unwrap_or_else(|_| root.to_path_buf());
        self.projects.iter().find_map(|(k, v)| {
            let p = resolve_project_key(k);
            let p_canon = p.canonicalize().unwrap_or(p);
            if p_canon == canonical { Some(v) } else { None }
        })
    }

    /// Find the mutable project record matching `root`.
    #[allow(dead_code)]
    pub fn get_project_mut(&mut self, root: &Path) -> Option<&mut ProjectRecord> {
        let key = normalize_project_key(root);
        if self.projects.contains_key(&key) {
            return self.projects.get_mut(&key);
        }
        let canonical = root.canonicalize().unwrap_or_else(|_| root.to_path_buf());
        let found_key = self.projects.iter().find_map(|(k, _)| {
            let p = resolve_project_key(k);
            let p_canon = p.canonicalize().unwrap_or(p);
            if p_canon == canonical {
                Some(k.clone())
            } else {
                None
            }
        });
        if let Some(k) = found_key {
            self.projects.get_mut(&k)
        } else {
            None
        }
    }

    /// Ensure a project record exists for `root`, returning a mutable reference.
    pub fn ensure_project(&mut self, root: &Path) -> &mut ProjectRecord {
        let key = normalize_project_key(root);
        self.projects.entry(key).or_default()
    }

    /// Remove a project record for `root`.
    pub fn remove_project(&mut self, root: &Path) -> Option<ProjectRecord> {
        let key = normalize_project_key(root);
        if let Some(record) = self.projects.remove(&key) {
            return Some(record);
        }
        let canonical = root.canonicalize().unwrap_or_else(|_| root.to_path_buf());
        let found_key = self.projects.iter().find_map(|(k, _)| {
            let p = resolve_project_key(k);
            let p_canon = p.canonicalize().unwrap_or(p);
            if p_canon == canonical {
                Some(k.clone())
            } else {
                None
            }
        });
        found_key.and_then(|k| self.projects.remove(&k))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample_skill(name: &str, target: &str) -> SkillState {
        SkillState {
            name: name.to_owned(),
            source_rel: name.to_owned(),
            target: target.to_owned(),
            written_hash: "blake3:aaaa".to_owned(),
            source_hash: "blake3:bbbb".to_owned(),
            pinned: false,
            installed_at: 1_760_536_800,
            ..SkillState::default()
        }
    }

    #[test]
    fn load_missing_registry_is_empty() {
        let tmp = tempfile::tempdir().unwrap();
        let path = tmp.path().join("missing.toml");
        assert_eq!(Registry::load_from(&path).unwrap(), Registry::default());
    }

    #[test]
    fn roundtrip_registry_preserves_data() {
        let tmp = tempfile::tempdir().unwrap();
        let path = tmp.path().join("projects.toml");

        let mut registry = Registry::default();
        let record = registry.ensure_project(Path::new("/dummy/project"));
        record.target = Some(".agents/skills".to_owned());
        record.upsert(sample_skill("git-commit", ".agents/skills"));

        registry.save_to(&path).unwrap();
        let loaded = Registry::load_from(&path).unwrap();

        assert_eq!(registry, loaded);
        let content = fs::read_to_string(&path).unwrap();
        assert!(content.starts_with(HEADER));
        assert!(content.contains("git-commit"));
    }

    #[test]
    fn upsert_replaces_same_name_and_target() {
        let mut record = ProjectRecord::default();
        record.upsert(sample_skill("alpha", ".agents/skills"));
        assert_eq!(record.skills.len(), 1);

        let mut updated = sample_skill("alpha", ".agents/skills");
        updated.written_hash = "blake3:updated".to_owned();
        record.upsert(updated);

        assert_eq!(record.skills.len(), 1);
        assert_eq!(record.skills[0].written_hash, "blake3:updated");
    }

    #[test]
    fn remove_drops_entry() {
        let mut record = ProjectRecord::default();
        record.upsert(sample_skill("alpha", ".agents/skills"));
        assert!(record.remove("alpha", ".agents/skills").is_some());
        assert!(record.is_empty());
    }
}
